"""Compiles the Neonix renderer's own shaders (src/renderer/nx_*.hlsl) with fxc into
src/renderer/dx11_shader_code.h, so the DLL does not compile them at run time (the fixed-function pixel shader
took 7 s with D3DCompile). Run after changing an .hlsl file: python -I tools/build_renderer_shaders.py
fxc comes from the Windows 10 SDK (or set FXC to its path)."""
import glob, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..', 'src', 'renderer'))
OUT = os.path.join(SRC, 'dx11_shader_code.h')
SHADERS = [  # file, entry point, profile, array name
    ('nx_ff_vs.hlsl', 'main', 'vs_4_0', 'kFFVS'),
    ('nx_ff_ps.hlsl', 'main', 'ps_4_0', 'kFFPS'),
    ('nx_util.hlsl', 'BlitVS', 'vs_4_0', 'kBlitVS'),
    ('nx_util.hlsl', 'BlitPS', 'ps_4_0', 'kBlitPS'),
    ('nx_util.hlsl', 'ClearVS', 'vs_4_0', 'kClearVS'),
    ('nx_util.hlsl', 'ClearPS', 'ps_4_0', 'kClearPS'),
    ('nx_terrain.hlsl', 'TerrainVS', 'vs_4_0', 'kTerrainVS'),
    ('nx_terrain.hlsl', 'TerrainPS', 'ps_4_0', 'kTerrainPS'),
]


def fxc_path():
    if os.environ.get('FXC'):
        return os.environ['FXC']
    kits = glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe')
    if not kits:
        raise SystemExit('fxc.exe not found: install the Windows 10 SDK or set FXC')
    return sorted(kits)[-1]


def main():
    fxc = fxc_path()
    parts = ['/* Generated by tools/build_renderer_shaders.py from nx_*.hlsl (fxc /O3): do not edit. */',
             '#ifndef NEONIX_DX11_SHADER_CODE_H', '#define NEONIX_DX11_SHADER_CODE_H']
    with tempfile.TemporaryDirectory() as tmp:
        for file, entry, profile, name in SHADERS:
            obj = os.path.join(tmp, name + '.cso')
            r = subprocess.run([fxc, '/nologo', '/O3', '/T', profile, '/E', entry, '/I', SRC, '/Fo', obj,
                                os.path.join(SRC, file)], capture_output=True, text=True)
            if r.returncode:
                sys.stderr.write(r.stdout + r.stderr)
                raise SystemExit('fxc failed on %s %s' % (file, entry))
            data = open(obj, 'rb').read()
            parts.append('static const unsigned char %s[%d] = {' % (name, len(data)))
            for i in range(0, len(data), 24):
                parts.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
            parts.append('};')
            print('%-14s %-8s %6d bytes' % (name, profile, len(data)))
    parts.append('#endif')
    with open(OUT, 'w', newline='\r\n') as f:
        f.write('\n'.join(parts) + '\n')


main()
